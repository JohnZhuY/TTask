def translate(text: str, language: str) -> str:
    if language != "en_US" or not text:
        return text
    if text in ENGLISH:
        return ENGLISH[text]
    # Translate stable fragments in dynamic labels while preserving task names,
    # dates, numbers and messages supplied by the user.
    for source in sorted(ENGLISH, key=len, reverse=True):
        if source in text:
            text = text.replace(source, ENGLISH[source])
    return text
